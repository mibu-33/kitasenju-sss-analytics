const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('public/nov13-map.html','utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script,'Nov13 map JavaScript exists');
new Function(script[1]);
const image=fs.readFileSync('public/reference/tousenbo_20261113_floor.webp.base64.txt','utf8').trim();
assert.ok(image.length>100000,'screenshot asset not empty');
const raw=Buffer.from(image,'base64');
assert.equal(raw.toString('ascii',0,4),'RIFF','WebP RIFF header');
assert.equal(raw.toString('ascii',8,12),'WEBP','WebP signature');
const geo=JSON.parse(fs.readFileSync('public/reference/tousenbo_20261113_coords.json','utf8'));
assert.equal(geo.image_width,687);
assert.equal(geo.image_height,678);
assert.equal(geo.entries.length,451);
assert.equal(new Set(geo.entries.map(x=>x.number)).size,451,'no duplicate numbers');
assert.ok(geo.entries.every(x=>Number.isFinite(x.x)&&Number.isFinite(x.y)&&x.x>=0&&x.x<=687&&x.y>=0&&x.y<=678));
assert.ok(geo.entries.every(x=>x.floor==='1F'||x.floor==='2F'));
assert.ok(html.includes("data:image/webp;base64,"),'original image displayed without redrawing');
assert.ok(html.includes("差枚を重ねる"),'optional data overlay UI');
assert.ok(html.includes("1Fのみ")&&html.includes("2Fのみ"),'floor cropping UI');
assert.ok(html.includes("台番")&&html.includes("番号へ移動"),'seat finding UI');
const all=new Map(geo.entries.map(x=>[x.number,x]));
assert.ok(all.get(1).y<340&&all.get(1001).y<340);
assert.ok(all.get(602).y>=340&&all.get(2001).y>=340);
console.log('PASS: source screenshot, 451 coordinate markers, floor selection and optional heatmap are wired');
